// Package storage provides private object storage for processed player photos.
package storage

import (
	"context"
	"errors"
	"time"
)

var (
	ErrNotFound    = errors.New("photo not found")
	ErrInvalid     = errors.New("invalid photo storage input")
	ErrUnavailable = errors.New("photo storage unavailable")
)

// MaxObjectBytes bounds both uploads and downloads, independently of HTTP limits.
const MaxObjectBytes = 5 * 1024 * 1024

type Object struct {
	Key string
	// LastModified is zero if the provider omits it; cleanup uses game EndedAt.
	LastModified time.Time
}

// Store never exposes public bucket URLs. Upload/read keys are generated by the
// service; cleanup can enumerate literal external names inside game photos.
type Store interface {
	Put(context.Context, string, []byte) error
	Get(context.Context, string) ([]byte, error)
	// Delete handles literal photo namespace keys; unsafe serialization is a per-key error.
	Delete(context.Context, string) error
	// List returns a bounded batch, which may not exhaust the prefix. Cleanup
	// callers delete the returned objects and revisit the prefix on later sweeps.
	List(context.Context, string) ([]Object, error)
}
